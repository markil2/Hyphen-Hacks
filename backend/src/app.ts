import express from "express";
import cors from "cors";
import helmet from "helmet";
import rateLimit from "express-rate-limit";
import { config } from "./config";
import { authenticate } from "./auth";
import { errorHandler, notFound, ok } from "./http";
import { authRouter } from "./routes/auth";
import { babiesRouter } from "./routes/babies";
import { sleepRouter } from "./routes/sleep";
import { feedingsRouter } from "./routes/feedings";
import { diapersRouter } from "./routes/diapers";
import { dashboardRouter } from "./routes/dashboard";
import { supportRouter } from "./routes/support";
import { catalogRouter } from "./routes/catalog";
import { maternalRouter } from "./routes/maternal";
import { growthRouter } from "./routes/growth";
import { familiesRouter } from "./routes/families";
import { settingsRouter } from "./routes/settings";
import { babyTrackingRouter } from "./routes/babyTracking";
import { notesRouter } from "./routes/notes";
import { recipesRouter } from "./routes/recipes";
import { summaryRouter } from "./routes/summary";
import { statsRouter } from "./routes/stats";
import { weightsRouter } from "./routes/weights";
import { foodsRouter } from "./routes/foods";

export const app = express();
export const createRateLimiter = (limit: number) => rateLimit({ windowMs: config.RATE_LIMIT_WINDOW_MS, limit, standardHeaders: "draft-7", legacyHeaders: false });
app.disable("x-powered-by");
app.use(helmet());
app.use(cors({ origin: config.FRONTEND_ORIGIN, credentials: false }));
app.use(express.json({ limit: "100kb" }));
app.use("/api/auth", createRateLimiter(config.AUTH_RATE_LIMIT_MAX), authRouter);
app.get("/api/health", (_req, res) => ok(res, { status: "ok", demoMode: config.DEMO_MODE }));
app.use("/api", createRateLimiter(config.RATE_LIMIT_MAX));
app.use("/api", authenticate, babiesRouter, sleepRouter, feedingsRouter, diapersRouter, dashboardRouter, supportRouter, catalogRouter, maternalRouter, growthRouter, familiesRouter, settingsRouter, babyTrackingRouter, notesRouter, recipesRouter, summaryRouter, statsRouter, weightsRouter, foodsRouter);
app.use(notFound);
app.use(errorHandler);
